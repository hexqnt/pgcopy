#!/usr/bin/env python3
"""Проверяет CLI на собственном временном PostgreSQL и, опционально, старом бинарнике.

Запуск: python3 tests/postgres.py target/debug/pgcopy [/path/to/pgcopy-before]
Нужны PostgreSQL server tools, psql и zstd; initdb запускается обычным пользователем.
"""

import io
import itertools
import json
import os
from pathlib import Path
import re
import shutil
import socket
import subprocess
import sys
import tarfile
import tempfile


FIXTURE = r"""
CREATE SCHEMA src;
CREATE TABLE src.items (
    id bigserial PRIMARY KEY, identity_id bigint GENERATED BY DEFAULT AS IDENTITY,
    label text DEFAULT 'fresh', n integer NOT NULL DEFAULT 0, payload bytea,
    amount numeric(10,2), happened timestamp, active boolean
);
INSERT INTO src.items VALUES
    (7,100,E'quote, "line"\nстрока',3,'\x0001ff',12.34,'2026-01-02 03:04:05',true),
    (12,200,NULL,4,NULL,NULL,NULL,false);
CREATE TABLE src.empty (id serial, label text);
CREATE TYPE src.status AS ENUM ('new', 'quote''`');
CREATE TABLE src.details (
    id integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    item_id bigint REFERENCES src.items, status src.status DEFAULT 'new',
    doubled integer GENERATED ALWAYS AS (item_id::integer * 2) STORED
);
INSERT INTO src.details(item_id) SELECT 7 FROM generate_series(1,12);
COMMENT ON TABLE src.items IS E'Untrusted\n```\ncomment';
COMMENT ON COLUMN src.items.label IS 'Customer''s label';
CREATE TABLE src.base (id integer, label text);
INSERT INTO src.base VALUES (1,'one'), (2,'two');
CREATE VIEW src.inner_v AS SELECT id, label FROM src.base;
CREATE VIEW src.outer_v AS SELECT id, label FROM src.inner_v WHERE id > 1;
CREATE MATERIALIZED VIEW src.materialized AS SELECT * FROM src.base;
ANALYZE;
"""
OBJECTS = """
[[objects]]
select = 'select * from src.items order by id'
target_schema = 'dst'
target_name = 'items'
[[objects]]
select = 'select id, label from src.items where id > 7 order by id limit 1'
target_schema = 'dst'
target_name = 'filtered'
[[objects]]
select = 'select * except (payload) from src.items order by id'
target_schema = 'dst'
target_name = 'excluded'
[[objects]]
select = 'select * from src.empty'
target_schema = 'dst'
target_name = 'empty'
"""


def command(args, env=None, data=None, success=True, executable=None):
    result = subprocess.run(list(map(str, args)), input=data, capture_output=True, env=env,
                            executable=executable)
    assert (result.returncode == 0) == success, (
        f"Unexpected exit {result.returncode}: {' '.join(map(str, args))}\n"
        + result.stderr.decode(errors="replace")
    )
    return result


def archive(path):
    raw = command(["zstd", "-q", "-d", "-c", path]).stdout
    with tarfile.open(fileobj=io.BytesIO(raw)) as bundle:
        return [(entry.name, bundle.extractfile(entry).read()) for entry in bundle]


def normalized_archive(entries):
    return [(name, re.sub(rb'("created_at": ")[^"]+("\s*[,}])', rb'\1<TIME>\2', data)
             if name == "manifest.json" else data) for name, data in entries]


def corrupt_copy(entries, path):
    output = io.BytesIO()
    with tarfile.open(fileobj=output, mode="w") as bundle:
        for name, data in entries:
            if name.startswith("data/"):
                data = b"invalid COPY payload\n"
            entry = tarfile.TarInfo(name)
            entry.size = len(data)
            bundle.addfile(entry, io.BytesIO(data))
    path.write_bytes(command(["zstd", "-q", "-c"], data=output.getvalue()).stdout)


class Database:
    def __init__(self, root):
        self.root = root
        bindir = command(["pg_config", "--bindir"]).stdout.decode().strip()
        self.initdb = shutil.which("initdb") or str(Path(bindir) / "initdb")
        self.pg_ctl = shutil.which("pg_ctl") or str(Path(bindir) / "pg_ctl")
        self.data = root / "postgres"
        self.env = {key: value for key, value in os.environ.items()
                    if not key.startswith("PG") and key not in {"PASSWORD", "RUST_LOG"}}
        with socket.socket() as listener:
            listener.bind(("127.0.0.1", 0))
            port = listener.getsockname()[1]
        self.env.update(PGHOST="127.0.0.1", PGPORT=str(port), PGUSER="pgcopy_test",
                        PGDATABASE="postgres", NO_COLOR="1", RUST_LOG="error",
                        RUST_BACKTRACE="0", RUST_LIB_BACKTRACE="0")
        command([self.initdb, "-D", self.data, "-A", "trust", "-U", "pgcopy_test",
                 "--no-locale", "-E", "UTF8"], env=self.env)
        command([self.pg_ctl, "-D", self.data, "-l", root / "postgres.log", "-w", "start",
                 "-o", f"-F -p {port} -k {root} -h 127.0.0.1"], env=self.env)

    def close(self):
        command([self.pg_ctl, "-D", self.data, "-w", "-m", "immediate", "stop"], env=self.env)

    def sql(self, sql, database="source"):
        return command(["psql", "-X", "-qAt", "-v", "ON_ERROR_STOP=1", "-d", database],
                       env=self.env, data=sql.encode()).stdout.decode().strip()

    def run(self, binary, *args, database="source", success=True):
        env = self.env | {"PGDATABASE": database}
        return command(["pgcopy", "--quiet", "--no-progress", *args], env=env,
                       success=success, executable=binary)

    def rows(self, table, database):
        return self.sql(f"SELECT coalesce(json_agg(t ORDER BY id)::text, '[]') FROM {table} t", database)

    def reset(self, database):
        self.sql("DROP SCHEMA IF EXISTS dst CASCADE; CREATE SCHEMA dst", database)


def check_binary(db, binary, target):
    db.sql(f"CREATE DATABASE {target}", "postgres")
    report = {}
    stable_exports = {}
    for data_format, snapshot, export_workers in itertools.product(["binary", "csv"], [True, False], [1, 3]):
        key = f"{data_format}-snapshot{int(snapshot)}-c{export_workers}"
        config = db.root / "config.toml"
        config.write_text(f'[general]\ndata_format = "{data_format}"\nconsistent_snapshot = {str(snapshot).lower()}\n' + OBJECTS)
        bundle = db.root / "bundle.tar.zst"
        db.run(binary, "export", "--config", config, "--out", bundle, "--concurrency", export_workers)
        entries = archive(bundle)
        report[key] = normalized_archive(entries)
        stable_key = (data_format, snapshot)
        if export_workers == 1:
            stable_exports[stable_key] = report[key]
        else:
            assert report[key] == stable_exports[stable_key], f"Parallel export differs: {key}"
        for import_workers in [1, 3]:
            args = ["import", "--in", bundle, "--concurrency", import_workers]
            db.reset(target)
            db.run(binary, *args, database=target)
            assert db.rows("dst.items", target) == db.rows("src.items", "source"), key
            assert db.sql("SELECT count(*) FROM dst.filtered", target) == "1", key
            assert db.sql("SELECT count(*) FROM dst.excluded", target) == "2", key
            db.sql("ALTER TABLE dst.items ALTER COLUMN identity_id ADD GENERATED BY DEFAULT AS IDENTITY", target)
            assert db.sql("INSERT INTO dst.empty(label) VALUES ('first') RETURNING id", target) == "1", key
            db.run(binary, *args, "--mode", "append", database=target)
            assert db.sql("SELECT count(*) FROM dst.items", target) == "4", key
            assert db.sql("INSERT INTO dst.items(label) VALUES ('next') RETURNING id,identity_id", target) == "13|201", key
            db.reset(target)
            db.run(binary, *args, "--ddl-only", database=target)
            assert db.sql("SELECT count(*) FROM dst.items", target) == "0", key
            assert db.sql("SELECT count(*) FROM dst.filtered", target) == "0", key

        for output_format, objects in itertools.product(["text", "json"], [False, True]):
            result = db.run(binary, "info", "--in", bundle, "--format", output_format, *(["--objects"] if objects else []))
            report[f"{key}-info-{output_format}-{objects}"] = re.sub(
                rb'(created_at[": ]+)[^\n"]+', rb'\1<TIME>', result.stdout)
        for operation in ["export", "import", "describe"]:
            args = ["--config", config, "--out", bundle] if operation == "export" else (
                ["--in", bundle] if operation == "import" else ["--config", config, "--no-format"])
            report[f"{key}-dry-{operation}"] = db.run(binary, operation, *args, "--dry-run").stderr

        broken = db.root / "broken.tar.zst"
        corrupt_copy(entries, broken)
        for workers in [1, 3]:
            db.reset(target)
            db.sql("CREATE TABLE dst.items(marker text); INSERT INTO dst.items VALUES ('preserved')", target)
            db.run(binary, "import", "--in", broken, "--concurrency", workers, database=target, success=False)
            assert db.sql("SELECT marker FROM dst.items", target) == "preserved", key

    config = db.root / "describe.toml"
    config.write_text(OBJECTS + "\n" + "\n".join(
        f"[[objects]]\nselect = 'select * from src.{name}'" for name in ["details", "inner_v", "materialized"]))
    for output_format, profile, comments in itertools.product(["markdown", "sql", "json"], [None, "basic", "3"], [True, False]):
        args = (["--statistics"] if profile == "basic" else [f"--statistics={profile}"] if profile else [])
        if not comments:
            args.append("--no-comments")
        report[f"describe-{output_format}-{profile}-{comments}"] = db.run(
            binary, "describe", "--config", config, "--format", output_format, "--no-format", *args).stdout

    config = db.root / "views.toml"
    config.write_text("[[objects]]\nselect = 'select * from src.outer_v'\nexport_as = 'view'\n")
    bundle = db.root / "views.tar.zst"
    for workers in [1, 3]:
        db.run(binary, "export", "--config", config, "--out", bundle, "--concurrency", workers)
        entries = archive(bundle)
        report[f"views-c{workers}"] = normalized_archive(entries)
        manifest = json.loads(entries[0][1])
        assert [obj["source_name"] for obj in manifest["objects"]] == ["base", "inner_v", "outer_v"]
        db.sql("DROP SCHEMA IF EXISTS src CASCADE", target)
        db.run(binary, "import", "--in", bundle, database=target)
        assert db.rows("src.outer_v", target) == db.rows("src.outer_v", "source")
        assert db.sql("SELECT relkind FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace WHERE n.nspname='src' AND c.relname='inner_v'", target) == "r"

    for arguments in [["--help"], ["export", "--help"], ["describe", "--help"],
                      ["import", "--in", bundle, "--concurrency", "0"],
                      ["describe", "--config", config, "--statistics=0"],
                      ["export", "--config", config, "--out", bundle, "--concurrency", "invalid"]]:
        result = db.run(binary, *arguments, success="--help" in arguments)
        report["cli-" + " ".join(map(str, arguments))] = (result.returncode, result.stdout, result.stderr)

    base = "[[objects]]\nselect = 'select * from src.base'\n"
    filtered = "[[objects]]\nselect = 'select * from src.base where id > 1'\n"
    outer = "[[objects]]\nselect = 'select * from src.outer_v'\nexport_as = 'view'\n"
    inner = "[[objects]]\nselect = 'select * from src.inner_v'\nexport_as = 'view'\n"
    for name, objects in [
        ("filtered-dependency", filtered + outer),
        ("filtered-after-dependency", outer + filtered),
        ("view-after-dependency", outer + inner),
        ("compatible-then-incompatible", base + filtered + outer),
    ]:
        config.write_text(objects)
        result = db.run(binary, "export", "--config", config, "--out", bundle, success=False)
        report[name] = (result.returncode, result.stdout, result.stderr)
    return report


def check_encryption(db, binaries):
    config = db.root / "encryption.toml"
    config.write_text("[[objects]]\nselect = 'select * from src.items order by id'\n"
                      "target_schema = 'dst'\ntarget_name = 'items'\n")
    bundle = db.root / "encrypted.age"
    password = "pgcopy-integration-password"
    db.run(binaries[0], "export", "--config", config, "--out", bundle, "--password", password)
    reports = []
    for index, binary in enumerate(binaries):
        args = ["info", "--in", bundle, "--format", "json"]
        info = db.run(binary, *args, "--password", password).stdout
        assert json.loads(info)["encrypted"]
        missing = db.run(binary, *args, success=False).stderr
        wrong = db.run(binary, *args, "--password", "wrong", success=False).stderr
        reports.append((info, missing, wrong))
        target = f"target_{index}"
        for workers in [1, 3]:
            db.reset(target)
            db.run(binary, "import", "--in", bundle, "--password", password,
                   "--concurrency", workers, database=target)
            assert db.rows("dst.items", target) == db.rows("src.items", "source")
    assert all(report == reports[0] for report in reports), "Encrypted bundle regression"


def main():
    if len(sys.argv) not in [2, 3]:
        raise SystemExit("Usage: python3 tests/postgres.py CURRENT_BINARY [BASELINE_BINARY]")
    binaries = [Path(value).resolve(strict=True) for value in sys.argv[1:]]
    with tempfile.TemporaryDirectory(prefix="pgcopy-pg-") as temporary:
        db = Database(Path(temporary))
        try:
            db.sql("CREATE DATABASE source", "postgres")
            db.sql(FIXTURE)
            reports = [check_binary(db, binary, f"target_{index}") for index, binary in enumerate(binaries)]
            check_encryption(db, binaries)
            if len(reports) == 2:
                assert reports[0].keys() == reports[1].keys()
                for key in reports[0]:
                    assert reports[0][key] == reports[1][key], f"Baseline regression: {key}"
            print(f"PostgreSQL integration passed: {len(binaries)} binary(s), {len(reports[0])} comparable results each")
        finally:
            db.close()


if __name__ == "__main__":
    main()
